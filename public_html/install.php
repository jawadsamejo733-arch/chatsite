<?php
/**
 * ChatSite one-time installer. Open https://your-domain/install.php after uploading the files.
 * It checks the server, creates the database tables and writes app/config.php.
 * Once app/config.php exists this page refuses to run again; you can then delete it.
 */
declare(strict_types=1);

require __DIR__ . '/app/bootstrap.php';

header('X-Content-Type-Options: nosniff');
header('X-Frame-Options: DENY');
header('Cache-Control: no-store');

$configFile = APP_DIR . '/config.php';
$installed = is_file($configFile);
$errors = [];
$done = false;
$manualConfig = null;

$checks = [
    ['PHP 8.1 or newer', PHP_VERSION_ID >= 80100, 'You have PHP ' . PHP_VERSION . '. Change it in cPanel → Select PHP Version.'],
    ['PDO MySQL extension', extension_loaded('pdo_mysql'), 'Enable "pdo_mysql" in cPanel → Select PHP Version → Extensions.'],
    ['Zip extension (custom website uploads)', class_exists('ZipArchive'), 'Enable "zip" in cPanel → Select PHP Version → Extensions.'],
    ['cURL extension (sending SMS)', function_exists('curl_init'), 'Enable "curl" in cPanel → Select PHP Version → Extensions.'],
    ['Fileinfo extension (image uploads)', class_exists('finfo'), 'Enable "fileinfo" in cPanel → Select PHP Version → Extensions.'],
    ['mbstring extension', function_exists('mb_strlen'), 'Recommended: enable "mbstring" in cPanel → Select PHP Version → Extensions.'],
    ['storage/ folder is writable', is_writable(PUBLIC_DIR . '/storage'), 'In File Manager, set the permissions of the "storage" folder to 755.'],
    ['app/ folder is writable (to save config.php)', is_writable(APP_DIR), 'Set "app" to 755, or create app/config.php by hand (shown after install).'],
];
$blocking = array_filter($checks, fn($c) => !$c[1] && !str_starts_with($c[0], 'mbstring') && !str_starts_with($c[0], 'app/'));

$v = fn(string $k, string $d = '') => e($_POST[$k] ?? $d);

if (!$installed && ($_SERVER['REQUEST_METHOD'] ?? '') === 'POST' && !$blocking) {
    $appName = clean_text($_POST['app_name'] ?? 'ChatSite', 40) ?: 'ChatSite';
    $cc = preg_replace('/\D+/', '', (string)($_POST['country_code'] ?? '1')) ?: '1';
    $dbHost = trim((string)($_POST['db_host'] ?? 'localhost')) ?: 'localhost';
    $dbName = trim((string)($_POST['db_name'] ?? ''));
    $dbUser = trim((string)($_POST['db_user'] ?? ''));
    $dbPass = (string)($_POST['db_pass'] ?? '');
    $driver = in_array($_POST['sms_driver'] ?? '', ['twilio', 'http', 'log'], true) ? $_POST['sms_driver'] : 'twilio';

    if ($dbName === '' || $dbUser === '') {
        $errors[] = 'Enter the database name and database user from cPanel → MySQL Databases.';
    }
    $sms = ['driver' => $driver];
    if ($driver === 'twilio') {
        $sms['twilio'] = [
            'sid' => trim((string)($_POST['tw_sid'] ?? '')),
            'token' => trim((string)($_POST['tw_token'] ?? '')),
            'from' => trim((string)($_POST['tw_from'] ?? '')),
            'messaging_service_sid' => trim((string)($_POST['tw_service'] ?? '')),
        ];
        if ($sms['twilio']['sid'] === '' || $sms['twilio']['token'] === '' || ($sms['twilio']['from'] === '' && $sms['twilio']['messaging_service_sid'] === '')) {
            $errors[] = 'Enter your Twilio Account SID, Auth Token and a sender number (or Messaging Service SID).';
        }
    }

    if (!$errors) {
        $dsn = 'mysql:host=' . $dbHost . ';dbname=' . $dbName . ';charset=utf8mb4';
        try {
            $pdo = Db::connect($dsn, $dbUser, $dbPass);
            Db::migrate($pdo);
        } catch (Throwable $ex) {
            $errors[] = 'Could not connect to the database: ' . $ex->getMessage()
                . ' — check the name, user and password, and that the user was added to the database with ALL PRIVILEGES.';
        }
    }

    if (!$errors) {
        $config = [
            'app_name' => $appName,
            'env' => $driver === 'log' ? 'development' : 'production',
            'app_secret' => bin2hex(random_bytes(32)),
            'db' => ['dsn' => $dsn, 'user' => $dbUser, 'pass' => $dbPass],
            'default_country_code' => $cc,
            'sms' => $sms,
            'test_numbers' => [],
        ];
        $php = "<?php\n// Generated by install.php on " . gmdate('Y-m-d H:i') . " UTC. See config.sample.php for every option.\nreturn "
            . var_export($config, true) . ";\n";
        foreach (['', 'logs', 'sessions', 'sites'] as $dir) {
            @mkdir(PUBLIC_DIR . '/storage/' . $dir, 0755, true);
        }
        if (@file_put_contents($configFile, $php, LOCK_EX) !== false) {
            @chmod($configFile, 0640);
            $done = true;
        } else {
            $manualConfig = $php;
        }
    }
}
$appUrl = base_path();
